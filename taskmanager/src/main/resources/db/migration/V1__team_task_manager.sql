CREATE TABLE app_users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 username VARCHAR(40) NOT NULL UNIQUE,
 password_hash VARCHAR(100) NOT NULL
);
CREATE TABLE projects (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(120) NOT NULL,
 owner_id BIGINT NOT NULL REFERENCES app_users(id)
);
CREATE TABLE memberships (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 project_id BIGINT NOT NULL REFERENCES projects(id),
 user_id BIGINT NOT NULL REFERENCES app_users(id),
 UNIQUE(project_id,user_id)
);
CREATE INDEX idx_memberships_user ON memberships(user_id);
CREATE TABLE tasks (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 project_id BIGINT NOT NULL REFERENCES projects(id),
 author_id BIGINT NOT NULL REFERENCES app_users(id),
 title VARCHAR(255) NOT NULL,
 description VARCHAR(2000),
 assignee_id BIGINT REFERENCES app_users(id),
 reviewer_id BIGINT REFERENCES app_users(id),
 status VARCHAR(20) NOT NULL CHECK(status IN ('TODO','IN_PROGRESS','REVIEW','DONE')),
 version BIGINT NOT NULL DEFAULT 0,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 CHECK(assignee_id IS NULL OR reviewer_id IS NULL OR assignee_id <> reviewer_id)
);
CREATE INDEX idx_tasks_project_status_id ON tasks(project_id,status,id);
CREATE INDEX idx_tasks_project_id ON tasks(project_id,id);
CREATE TABLE task_comments (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 task_id BIGINT NOT NULL REFERENCES tasks(id),
 author_id BIGINT NOT NULL REFERENCES app_users(id),
 body VARCHAR(2000) NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_comments_task_id ON task_comments(task_id,id);
CREATE TABLE task_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 task_id BIGINT NOT NULL REFERENCES tasks(id),
 actor_id BIGINT NOT NULL REFERENCES app_users(id),
 type VARCHAR(40) NOT NULL,
 details VARCHAR(5000) NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_events_task_id ON task_events(task_id,id);
